#!/usr/bin/env python3
"""Writes server/cards-copy.js — the words on the agents' digital cards
(/team/{slug}), from locales/en/cards.json and locales/es/cards.json.

    python3 tools/gencards.py

The cards are rendered by a Pages Function (server/cards.js), which cannot read
the catalogs at run time, so their words are compiled into a module here. Like
every other generator: change the catalogs, run this, commit both. Never edit
server/cards-copy.js by hand.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    copy = {}
    for lang in ('en', 'es'):
        with open(os.path.join(ROOT, 'locales', lang, 'cards.json'), encoding='utf-8') as f:
            copy[lang] = json.load(f)
    out = ('// Generated by tools/gencards.py from locales/*/cards.json — do not edit.\n'
           'export const COPY = ' + json.dumps(copy, ensure_ascii=False, indent=2, sort_keys=True) + ';\n')
    path = os.path.join(ROOT, 'server', 'cards-copy.js')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(out)
    print('  server/cards-copy.js')


if __name__ == '__main__':
    main()
